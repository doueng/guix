(ns keyguide-test
  (:require [clojure.test :refer [deftest is run-tests]]
            [clojure.edn :as edn]
            [clojure.string :as str]))
(load-file "desktop/bin/keyguide")
(require '[hypr.dispatch :as hypr])

(def registry
  (keyguide/validate!
   (keyguide/groups (edn/read-string (slurp "desktop/configs/keybindings/bindings.edn")))))

(deftest workspace-digits-expand-to-dispatchers
  (let [workspaces (:entries (second registry))]
    (is (= ["focus" {:workspace 10}] (keyguide/dispatcher (first workspaces))))
    (is (= ["window.move" {:workspace 3}] (keyguide/dispatcher (nth workspaces 13))))))

(deftest dispatchers-render-as-lua
  (is (= "hl.dsp.focus({ direction = \"left\" })" (hypr/lua ["focus" {:direction "left"}])))
  (is (= "hl.dsp.window.close()" (hypr/lua ["window.close"])))
  (is (= "hl.dsp.window.move({ follow = false, workspace = \"special:x\" })"
         (hypr/lua ["window.move" {:workspace "special:x" :follow false}])))
  (is (= "hl.dsp.exec_cmd(\"say \\\"hi\\\"\")" (hypr/lua ["exec_cmd" "say \"hi\""]))))

(deftest generated-lua-binds-and-logs-each-entry
  (is (= (str "-- Generated by keyguide --hypr. Edit keybindings/bindings.edn.\n"
              "local keys = require(\"keys\")\n"
              "keys.bind(\"CTRL + ALT + H\", hl.dsp.focus({ direction = \"left\" }), \"CTRL+ALT+H\", \"Focus left\")\n")
         (keyguide/hypr-config [{:entries [{:label "Focus left" :hypr ["CTRL ALT" "H" ["focus" {:direction "left"}]]}]}]))))

(deftest display-and-tips
  (is (= "h  Left   [CTRL+ALT+H]"
         (keyguide/line {:id "h" :label "Left" :hypr ["CTRL ALT" "H" ["focus" {:direction "left"}]]})))
  (is (= ["notify-send" "-a" "Keyguide" "-t" "12000" "Search" "Use / instead"]
         (keyguide/argv {:label "Search" :tip "Use / instead"}))))

(deftest desktop-chords-do-not-collide
  (let [chords (for [line (str/split-lines (str (slurp "desktop/configs/hypr/hyprland.lua")
                                                (slurp "desktop/configs/hypr/keybindings.lua")))
                     :let [[_ chord] (re-find #"^(?:hl|keys)\.bind\(\"([^\"]+)\"" line)]
                     :when chord]
                 (set (map str/upper-case (str/split chord #" \+ "))))]
    (is (= (count chords) (count (distinct chords))))
    (is (not-any? #(and (contains? % "ALT") (= 2 (count %)) (not (contains? % "SPACE"))) chords)
        "Alt plus a single key belongs to applications, except Alt+Space")))

(deftest reject-ambiguous-and-invalid-entries
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"Duplicate guide key"
        (keyguide/validate! [{:id "w"} {:id "w"}])))
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"exactly one action"
        (keyguide/validate! [{:id "w" :entries [{:id "h" :tip "tip" :command ["true"]}]}])))
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"Duplicate desktop shortcut"
        (keyguide/validate! [{:id "w" :entries [{:id "h" :hypr ["CTRL ALT" "H" ["focus" {:direction "left"}]]}
                                               {:id "j" :hypr ["CTRL ALT" "H" ["focus" {:direction "down"}]]}]}])))
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"Invalid Hyprland binding"
        (keyguide/validate! [{:id "w" :entries [{:id "h" :hypr ["CTRL ALT" "H" "movefocus" "l"]}]}]))
      "the old dispatcher strings are rejected"))

(let [{:keys [fail error]} (run-tests)]
  (System/exit (if (zero? (+ fail error)) 0 1)))
