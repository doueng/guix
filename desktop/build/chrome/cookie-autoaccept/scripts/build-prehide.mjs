// Writes src/prehide-selectors.js: the banner selectors the early content script hides before paint. From the
// vendored autoconsent rules that apply on any site, autoconsent's built-in CMP classes (copied here, since they are
// code in content.bundle.js, not data), the CMP table in src/cmps.js and a few generic patterns.
// Run by scripts/update-autoconsent.sh; test/prehide.test.js checks the file is current.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const ROOT = new URL('..', import.meta.url);

// content.bundle.js 18.5.0: prehideSelectors of its class-based CMPs and its global didomi list.
const BUILT_IN = [
  '.trustarc-banner-container', '.truste_popframe', '.truste_overlay', '.truste_box_overlay', '#truste-consent-track',
  '#CybotCookiebotDialog', '#CybotCookiebotDialogBodyUnderlay', '#dtcookie-container', '#cookiebanner', '#cb-cookieoverlay',
  '.modal--cookie-banner', '#cookiebanner_outer', '#CookieBanner',
  "div[id^='sp_message_container_']", '.message-overlay', '#sp_privacy_manager_container',
  '#cmpbox', '#cmpbox2',
  '#onetrust-banner-sdk', '#onetrust-consent-sdk', '.onetrust-pc-dark-filter', '.js-consent-banner',
  '.klaro', '.cmp-root',
  '#didomi-popup', '.didomi-popup-container', '.didomi-popup-notice', '.didomi-consent-popup-preferences', '#didomi-notice',
  '.didomi-popup-backdrop', '.didomi-screen-medium',
];
// Ids and classes that name a cookie banner. They can match other things; the early script releases them in seconds.
const GENERIC = [
  '[id*="cookie-banner" i]', '[class*="cookie-banner" i]', '[id*="cookie-consent" i]', '[class*="cookie-consent" i]',
  '[id*="cookie-notice" i]', '[class*="cookie-notice" i]', '[id*="cookiebanner" i]', '[class*="cookiebanner" i]',
];

/** The selector list, deduplicated, in a stable order. */
export function prehideSelectors() {
  const rules = JSON.parse(readFileSync(new URL('vendor/autoconsent/rules.json', ROOT))).autoconsent;
  const fromRules = rules
    .filter((r) => r.prehideSelectors?.length && !r.runContext?.urlPattern)
    .flatMap((r) => r.prehideSelectors.flatMap((s) => s.split(/,(?![^(]*\))/)))
    .map((s) => s.trim())
    .filter(Boolean);
  const ctx = vm.createContext({ btoa });
  vm.runInContext(readFileSync(new URL('src/cmps.js', ROOT), 'utf8'), ctx);
  const fromTable = ctx.cookieAutoaccept.CMPS.flatMap((c) => c.prehide);
  return [...new Set([...fromTable, ...BUILT_IN, ...fromRules, ...GENERIC])];
}

export function render(selectors) {
  return `// Generated by scripts/build-prehide.mjs from vendor/autoconsent and src/cmps.js. Do not edit.
globalThis.cookieAutoaccept = Object.assign(globalThis.cookieAutoaccept || {}, {
  prehideSelectors: ${JSON.stringify(selectors, null, 0).replace(/","/g, '",\n    "').replace(/^\[/, '[\n    ').replace(/\]$/, ',\n  ]')},
});
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sel = prehideSelectors();
  writeFileSync(new URL('src/prehide-selectors.js', ROOT), render(sel));
  console.log(`src/prehide-selectors.js: ${sel.length} selectors`);
}
